/**
 * Deterministic, local, zero-network fixture generation.
 *
 * A fixture is generated purely from manifest data: fixed file contents,
 * seeded generators, fixed git author and dates, and data-driven git
 * setup. Regenerating a task always produces a byte-identical tree, so
 * both evaluation arms can start from the same bytes.
 *
 * Git is driven with argv arrays through spawnSync (never a shell).
 */

import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";

const GIT_ENV = {
  GIT_CONFIG_GLOBAL: "/dev/null",
  GIT_CONFIG_NOSYSTEM: "1",
};

/** Deterministic 32-bit PRNG (mulberry32) so generated bytes are stable. */
function makeRandom(seed) {
  let state = seed >>> 0;
  return function random() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Generate the fixture for one task into `outDir` (created fresh).
 * Throws on any setup step that does not behave as declared.
 */
export function generateFixture({ repoRoot, task, outDir }) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  const fixture = task.fixture;
  for (const file of fixture.files) {
    writeJoined(outDir, file.path, file.content);
  }
  for (const entry of fixture.generate) {
    writeGenerated(outDir, entry);
  }

  runGit(outDir, ["init", "-q", "-b", "master"]);
  let currentBranch = "master";

  const startDate = Date.parse(fixture.git.startDate);
  if (!Number.isFinite(startDate)) {
    throw new Error(`task ${task.id}: invalid git.startDate`);
  }
  fixture.git.commits.forEach((commit, index) => {
    if (commit.branch && commit.branch !== currentBranch) {
      const branchArgs = ["checkout", "-q"];
      branchArgs.push(branchExists(outDir, commit.branch) ? commit.branch : "-b", commit.branch);
      if (branchArgs[2] === "-b") {
        runGit(outDir, ["checkout", "-q", "-b", commit.branch]);
      } else {
        runGit(outDir, ["checkout", "-q", commit.branch]);
      }
      currentBranch = commit.branch;
    }
    for (const edit of commit.edits ?? []) {
      applyEdit(outDir, task.id, edit);
    }
    const paths = commit.paths ?? ["all"];
    if (paths.includes("all")) {
      runGit(outDir, ["add", "-A", "."]);
    } else {
      runGit(outDir, ["add", ...paths]);
    }
    const when = new Date(startDate + index * 60_000).toISOString();
    runGit(
      outDir,
      [
        "-c",
        `user.name=${fixture.git.author.name}`,
        "-c",
        `user.email=${fixture.git.author.email}`,
        "commit",
        "-q",
        "-m",
        commit.message,
        "--date",
        when,
      ],
      { GIT_AUTHOR_DATE: when, GIT_COMMITTER_DATE: when },
    );
  });

  runGit(outDir, ["checkout", "-q", currentBranch]);
  for (const mutation of fixture.mutations) {
    applyEdit(outDir, task.id, mutation);
  }
  for (const file of fixture.untracked) {
    writeJoined(outDir, file.path, file.content);
  }
  if (fixture.git.post.some((step) => step.argv?.[1] === "merge")) {
    runGit(outDir, ["config", "user.name", fixture.git.author.name]);
    runGit(outDir, ["config", "user.email", fixture.git.author.email]);
  }
  for (const step of fixture.git.post) {
    runGit(outDir, step.argv.slice(1), {}, step.expectFailure, task.id);
  }
  const postconditions = validateFixturePostconditions({ task, fixtureDir: outDir });
  if (!postconditions.ok) {
    throw new Error(
      `task ${task.id}: generated fixture does not satisfy its declared postconditions:\n` +
        postconditions.errors.map((error) => `  - ${error}`).join("\n"),
    );
  }
  return outDir;
}

/**
 * Prepare one arm worktree for a task: a fresh copy of the deterministic
 * fixture plus the arm's session scaffold directory. Both arms receive
 * byte-identical worktrees; only directory names differ.
 */
export function prepareArmWorktree({ repoRoot, task, arm, parentDir }) {
  const fixtureDir = join(parentDir, "fixture");
  generateFixture({ repoRoot, task, outDir: fixtureDir });
  const armDir = join(parentDir, `arm-${arm}`);
  mkdirSync(armDir, { recursive: true });
  const worktree = join(armDir, "worktree");
  cpSync(fixtureDir, worktree, { recursive: true, dot: true });
  mkdirSync(join(armDir, "sessions"), { recursive: true });
  return armDir;
}

/** SHA-256 over the sorted relative paths and file bytes (skips .git). */
export function hashTree(dir) {
  const entries = [];
  collect(dir, "");
  entries.sort();
  const hash = createHash("sha256");
  for (const relative of entries) {
    hash.update(relative);
    hash.update("\0");
    hash.update(createHash("sha256").update(readFileSync(join(dir, relative))).digest("hex"));
    hash.update("\0");
  }
  return hash.digest("hex");

  function collect(current, prefix) {
    for (const name of readdirSync(current)) {
      if (name === ".git") continue;
      const absolute = join(current, name);
      const relative = prefix ? `${prefix}/${name}` : name;
      if (statSync(absolute).isDirectory()) {
        collect(absolute, relative);
      } else {
        entries.push(relative);
      }
    }
  }
}

/**
 * Apply a reference solution to a worktree: write the solution files,
 * then run the solution commands sequentially with argv arrays (never a
 * shell). Git commands receive a fixed fallback identity through the
 * environment so commits work without any global configuration.
 */
export function applySolution({ worktree, solution, taskId = "solution" }) {
  for (const file of solution.files) {
    writeJoined(worktree, file.path, file.content);
  }
  for (const command of solution.commands) {
    const result = spawnSync(command[0], command.slice(1), {
      cwd: worktree,
      encoding: "utf8",
      env: {
        PATH: process.env.PATH ?? "/usr/bin:/bin",
        HOME: worktree,
        GIT_CONFIG_GLOBAL: "/dev/null",
        GIT_CONFIG_NOSYSTEM: "1",
        GIT_AUTHOR_NAME: "Reference Solution",
        GIT_AUTHOR_EMAIL: "solution@example.invalid",
        GIT_COMMITTER_NAME: "Reference Solution",
        GIT_COMMITTER_EMAIL: "solution@example.invalid",
      },
    });
    if (result.status !== 0) {
      throw new Error(
        `task ${taskId}: solution command ${JSON.stringify(command)} failed with ` +
          `status ${result.status}: ${(result.stderr || result.stdout || "").slice(0, 400)}`,
      );
    }
  }
}

function writeJoined(root, relativePath, content) {
  const target = join(root, relativePath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content, "utf8");
}

/**
 * Validate that a fixture still matches the initial conditions its task
 * declared in the manifest: staged paths stay staged, mutated paths stay
 * modified, untracked paths stay untracked, and a declared failed merge
 * still has MERGE_HEAD plus conflict markers. Purely local reads plus a
 * `git status` call with argv arrays; never a shell.
 */
export function validateFixturePostconditions({ task, fixtureDir }) {
  const errors = [];
  const status = porcelainLines(fixtureDir);
  const stagedDeclared = [];
  const mergeDeclared = [];
  for (const step of task.fixture.git.post) {
    const argv = step.argv ?? [];
    if (argv[0] === "git" && argv[1] === "add") {
      stagedDeclared.push(...argv.slice(2));
    }
    if (argv.includes("merge") && step.expectFailure) {
      mergeDeclared.push({ argv, conflictPaths: Array.isArray(step.conflictPaths) ? step.conflictPaths : [] });
    }
  }
  for (const path of stagedDeclared) {
    if (!status.some((line) => isStagedEntry(line, path))) {
      errors.push(`fixture postcondition failed: ${path} must be staged but git status shows no staged entry`);
    }
  }
  for (const mutation of task.fixture.mutations) {
    if (!status.some((line) => entryMatches(line, mutation.path))) {
      errors.push(`fixture postcondition failed: ${mutation.path} must be modified but git status shows no change`);
    }
  }
  for (const file of task.fixture.untracked) {
    if (!status.some((line) => untrackedMatches(line, file.path))) {
      errors.push(`fixture postcondition failed: ${file.path} must be untracked but git status shows no untracked entry`);
    }
  }
  if (mergeDeclared.length > 0) {
    errors.push(...validateMergeConflictState({ task, fixtureDir, mergeDeclared }));
  }
  return { ok: errors.length === 0, errors };
}

/**
 * Validate every precondition a declared failed merge must leave in a
 * fixture: MERGE_HEAD present and equal to the intended branch head,
 * unmerged index stages 1/2/3 for each declared conflict path, an
 * unmerged status entry, and conflict markers in that path's working
 * file. Without a conflictPaths declaration the merge's actual unmerged
 * paths are used, plus the generic conflict-marker check.
 */
function validateMergeConflictState({ fixtureDir, mergeDeclared }) {
  const errors = [];
  for (const step of mergeDeclared) {
    const branch = step.argv[2];
    if (typeof branch !== "string" || branch.length === 0) {
      errors.push(`fixture postcondition failed: declared failed merge must name a branch (got ${JSON.stringify(branch)})`);
      continue;
    }
    if (!existsSync(join(fixtureDir, ".git", "MERGE_HEAD"))) {
      errors.push("fixture postcondition failed: declared failed merge must leave .git/MERGE_HEAD");
      continue;
    }
    const branchHead = spawnSync("git", ["rev-parse", `refs/heads/${branch}`], gitOptions(fixtureDir));
    if (branchHead.status !== 0) {
      errors.push(
        `fixture postcondition failed: declared merge branch ${branch} must resolve to a commit`,
      );
      continue;
    }
    const mergeHead = readFileSync(join(fixtureDir, ".git", "MERGE_HEAD"), "utf8").trim();
    const intended = branchHead.stdout.trim();
    if (mergeHead !== intended) {
      errors.push(
        `fixture postcondition failed: .git/MERGE_HEAD must point at the head of the intended branch ${branch} ` +
          `(got ${mergeHead}, intended ${intended})`,
      );
    }

    const declared = step.conflictPaths;
    const paths = declared.length > 0
      ? declared
      : [...unmergedPaths(fixtureDir)];
    if (declared.length === 0 && paths.length === 0 && !containsConflictMarkers(fixtureDir)) {
      errors.push("fixture postcondition failed: declared failed merge must leave conflict markers in tracked files");
    }
    const status = porcelainLines(fixtureDir);
    for (const path of paths) {
      const stages = unmergedStages(fixtureDir, path);
      if (stages.join(",") !== "1,2,3") {
        errors.push(
          `fixture postcondition failed: merge conflict path ${path} must hold unmerged index stages 1, 2, and 3 ` +
            `(got [${stages.join(", ")}])`,
        );
      }
      if (!status.some((line) => isUnmergedEntry(line, path))) {
        errors.push(`fixture postcondition failed: merge conflict path ${path} must keep an unmerged status entry`);
      }
      const working = readWorkingFile(fixtureDir, path);
      if (working === null || !hasAllConflictMarkers(working)) {
        errors.push(
          `fixture postcondition failed: merge conflict path ${path} must keep conflict markers ` +
            "<<<<<<<, =======, and >>>>>>>",
        );
      }
    }
  }
  return errors;
}

/** Sorted stage numbers of one path's unmerged index entries. */
function unmergedStages(fixtureDir, path) {
  const result = spawnSync("git", ["ls-files", "--unmerged", "--", path], gitOptions(fixtureDir));
  if (result.status !== 0) return [];
  return (result.stdout ?? "")
    .split("\n")
    .filter((line) => line.trim().length > 0)
    .map((line) => Number(line.split("\t")[0].split(" ")[2]))
    .sort((a, b) => a - b);
}

/** Every path with unmerged index entries. */
function unmergedPaths(fixtureDir) {
  const result = spawnSync("git", ["ls-files", "--unmerged"], gitOptions(fixtureDir));
  if (result.status !== 0) return [];
  const paths = new Set();
  for (const line of (result.stdout ?? "").split("\n")) {
    const path = line.slice(line.indexOf("\t") + 1).trim();
    if (path.length > 0) paths.add(path);
  }
  return paths;
}

/** A porcelain entry is unmerged when either status column is U or both sides changed (AA/DD). */
function isUnmergedEntry(line, path) {
  if (line.length < 4) return false;
  const code = line.slice(0, 2);
  if (!/^(UU|AA|DD|AU|UA|DU|UD)$/.test(code)) return false;
  return entryPath(line) === path;
}

function readWorkingFile(fixtureDir, path) {
  try {
    return readFileSync(join(fixtureDir, path), "utf8");
  } catch {
    return null;
  }
}

/** A conflicted working file must carry all three marker kinds. */
function hasAllConflictMarkers(text) {
  return text.includes("<<<<<<<") && text.includes("=======") && text.includes(">>>>>>>");
}

function porcelainLines(fixtureDir) {
  const result = spawnSync("git", ["status", "--porcelain"], gitOptions(fixtureDir));
  if (result.status !== 0) {
    throw new Error(`cannot read git status of fixture ${fixtureDir}: ${result.stderr ?? ""}`);
  }
  return (result.stdout ?? "").split("\n").filter((line) => line.trim().length > 0);
}

function isStagedEntry(line, path) {
  if (line.length < 4) return false;
  const code = line.slice(0, 2);
  if (code[0] === " " || code[0] === "?") return false;
  return entryPath(line) === path;
}

function entryMatches(line, path) {
  return entryPath(line) === path;
}

function untrackedMatches(line, path) {
  if (!line.startsWith("?? ")) return false;
  const shown = entryPath(line);
  return shown === path || path.startsWith(shown.endsWith("/") ? shown : shown + "/");
}

function entryPath(line) {
  return line.slice(3).replace(/^"/, "").replace(/"$/, "").trimEnd();
}

function containsConflictMarkers(fixtureDir) {
  const stack = [""];
  while (stack.length > 0) {
    const prefix = stack.pop();
    for (const name of readdirSync(join(fixtureDir, prefix))) {
      if (name === ".git") continue;
      const relative = prefix ? `${prefix}/${name}` : name;
      const absolute = join(fixtureDir, relative);
      if (statSync(absolute).isDirectory()) {
        stack.push(relative);
      } else if (readFileSync(absolute, "utf8").includes("<<<<<<<")) {
        return true;
      }
    }
  }
  return false;
}

/**
 * Git-state hash: HEAD commit plus the porcelain status lines. Together
 * with the content tree hash this pins the exact starting bytes of an
 * attempt so pairs can refuse to run from divergent fixtures.
 */
export function gitStateSnapshot(fixtureDir) {
  const head = spawnSync("git", ["rev-parse", "HEAD"], gitOptions(fixtureDir));
  if (head.status !== 0) {
    throw new Error(`cannot read HEAD of fixture ${fixtureDir}: ${head.stderr ?? ""}`);
  }
  return {
    head: head.stdout.trim(),
    porcelain: porcelainLines(fixtureDir),
  };
}

export function gitStateHash(fixtureDir) {
  const snapshot = gitStateSnapshot(fixtureDir);
  const hash = createHash("sha256");
  hash.update(snapshot.head);
  hash.update("\0");
  hash.update(snapshot.porcelain.join("\n"));
  return hash.digest("hex");
}

function applyEdit(root, taskId, edit) {
  const target = join(root, edit.path);
  const before = readFileSync(target, "utf8");
  const occurrences = before.split(edit.from).length - 1;
  if (occurrences !== 1) {
    throw new Error(
      `task ${taskId}: edit anchor in ${edit.path} matched ${occurrences} times, expected exactly 1`,
    );
  }
  writeFileSync(target, before.replace(edit.from, edit.to), "utf8");
}

function branchExists(root, branch) {
  const result = spawnSync(
    "git",
    ["rev-parse", "--verify", "-q", `refs/heads/${branch}`],
    gitOptions(root),
  );
  return result.status === 0;
}

function runGit(root, argv, extraEnv = {}, expectFailure = false, taskId = "fixture") {
  const result = spawnSync("git", argv, gitOptions(root, extraEnv));
  const failed = result.status !== 0;
  if (failed && !expectFailure) {
    throw new Error(
      `task ${taskId}: git ${argv.join(" ")} failed with status ${result.status}: ` +
        `${result.stderr ?? ""}`,
    );
  }
  if (!failed && expectFailure) {
    throw new Error(
      `task ${taskId}: git ${argv.join(" ")} was declared expectFailure but succeeded`,
    );
  }
  return result;
}

function gitOptions(root, extraEnv = {}) {
  return {
    cwd: root,
    encoding: "utf8",
    env: {
      PATH: process.env.PATH ?? "/usr/bin:/bin",
      ...GIT_ENV,
      ...extraEnv,
    },
  };
}

function writeGenerated(root, entry) {
  const random = makeRandom(entry.seed);
  if (entry.path.includes("<NN>")) {
    for (let index = 0; index < entry.count; index += 1) {
      const padded = String(index).padStart(2, "0");
      const path = entry.path.replace("<NN>", padded);
      writeJoined(root, path, renderTemplate(entry.template, index, entry.seed, random));
    }
    return;
  }
  const lines = [];
  for (let index = 0; index < entry.count; index += 1) {
    lines.push(renderTemplate(entry.template, index, entry.seed, random, true));
  }
  writeJoined(root, entry.path, lines.join(""));
}

function renderTemplate(template, index, seed, random, lineMode = false) {
  switch (template) {
    case "python-module":
      return pythonModule(index, seed, random);
    case "js-service":
      return jsService(index, seed, random);
    case "log-lines":
      return logLine(index, random);
    case "jsonl-events":
      return jsonlEvent(index, random);
    default:
      throw new Error(`unknown generator template ${template}`);
  }
}

function pythonModule(index, seed, random) {
  const padded = String(index).padStart(2, "0");
  const lines = [
    `"""Generated support module ${padded} for the pipeline fixture.`,
    "",
    "Deterministic filler used by the paired evaluation. Do not edit by hand.",
    `Seed: ${seed}.`,
    `Module index: ${index}.`,
    `Weight hint: ${(random() * 100).toFixed(2)}.`,
    '"""',
    "",
    "REGISTRY = {",
    `    "module": "${padded}",`,
    `    "seed": "${seed}",`,
    '    "modes": ["scan", "fold", "emit"],',
    `    "limits": {"max_items": ${1000 + index}, "depth": ${(index % 7) + 1}},`,
    "}",
    "",
    "",
    `def handler_${index}(value):`,
    '    """Apply the module transform to one value."""',
    "    return value * 2",
    "",
    "",
    `def describe_${index}():`,
    `    return "module ${padded} handler doubles values"`,
    "",
    "",
  ];
  for (let probe = 0; probe < 12; probe += 1) {
    lines.push(`def probe_${index}_${probe}(value):`);
    lines.push(`    """Probe ${probe} for module ${padded}."""`);
    lines.push(`    return value + ${probe * (index + 1) + (seed % 13)}`);
    lines.push("");
    lines.push("");
  }
  lines.push("FINGERPRINT = {");
  for (let bucket = 0; bucket < 8; bucket += 1) {
    lines.push(`    "bucket_${bucket}": ${Math.floor(random() * 1000)},`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function jsService(index, seed, random) {
  const padded = String(index).padStart(2, "0");
  const lines = [
    '"use strict";',
    "",
    `/** Generated service ${padded}. Deterministic evaluation filler. */`,
    `const SERVICE_ID = ${index};`,
    `const SERVICE_META = { id: ${index}, seed: ${seed}, mode: "fold" };`,
    "",
    "function mergeTotals(totals, entry) {",
    "  return { count: (totals.count + entry.count) | 0, sum: totals.sum + entry.sum };",
    "}",
    "",
  ];
  for (let probe = 0; probe < 10; probe += 1) {
    lines.push(`function probe${padded}_${probe}(value) {`);
    lines.push(`  return value + ${probe * (index + 2) + (seed % 17)};`);
    lines.push("}");
    lines.push("");
  }
  lines.push(`const FINGERPRINT = [${Array.from({ length: 8 }, () => Math.floor(random() * 1000)).join(", ")}];`);
  lines.push("");
  lines.push("module.exports = { SERVICE_ID, SERVICE_META, mergeTotals, FINGERPRINT };");
  lines.push("");
  return lines.join("\n");
}

function logLine(index, random) {
  const minute = String(Math.floor(index / 60) % 60).padStart(2, "0");
  const second = String(index % 60).padStart(2, "0");
  const level = random() < 0.9 ? "info" : "warn";
  if (index === 4172) {
    return (
      `2026-06-15T10:${minute}:${second}Z entry ${index} level=error ` +
      'incident="transform dropped trailing record" route=/api/v1/items ' +
      `handler=handler_${index % 45} status=500 bytes=${Math.floor(random() * 9000)}\n`
    );
  }
  return (
    `2026-06-15T10:${minute}:${second}Z entry ${index} level=${level} ` +
    `route=/api/v1/items handler=handler_${index % 45} ` +
    `status=${random() < 0.8 ? 200 : 204} bytes=${Math.floor(random() * 9000)}\n`
  );
}

function jsonlEvent(index, random) {
  const note = index === 417 ? "failing batch" : "audit";
  return (
    `{"id": ${index}, "count": 1, "sum": ${Math.floor(random() * 97)}, ` +
    `"service": "service-${String(index % 60).padStart(2, "0")}", "note": "${note}"}\n`
  );
}
